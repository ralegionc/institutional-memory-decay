"""Tests for the decay estimators.

The central claim these tests defend: when the data are generated by a known
decay law, the fitting code identifies that law and recovers its parameters.
Everything the project reports rests on that.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
import pytest

from imd import decay


def _poisson_series(model, params, n_months=180, seed=0):
    rng = np.random.default_rng(seed)
    t = np.arange(n_months, dtype=float)
    mu = model.predict(t, np.asarray(params, dtype=float))
    return t, rng.poisson(mu).astype(float)


def test_poisson_nll_penalises_wrong_parameters():
    model = decay.PowerLaw()
    t, y = _poisson_series(model, [300.0, 1.2], seed=1)
    good = decay.poisson_nll(np.array([300.0, 1.2]), model, t, y)
    bad = decay.poisson_nll(np.array([300.0, 0.2]), model, t, y)
    assert good < bad


@pytest.mark.parametrize(
    "model,params,tolerance",
    [
        (decay.PowerLaw(), [400.0, 1.30], 0.12),
        (decay.PowerLaw(), [150.0, 0.70], 0.12),
        (decay.Exponential(), [400.0, 18.0], 0.20),
    ],
)
def test_parameter_recovery(model, params, tolerance):
    t, y = _poisson_series(model, params, seed=7)
    fit = decay.fit_model(model, t, y, seed=7)
    assert fit["converged"]
    recovered = fit["_params"]
    for got, want in zip(recovered, params):
        assert abs(got - want) / want < tolerance, (got, want)


def test_model_selection_prefers_the_generating_form():
    """AICc should pick the family the data actually came from."""
    truth = decay.PowerLaw()
    t, y = _poisson_series(truth, [500.0, 1.1], n_months=200, seed=3)
    fits = {m.name: decay.fit_model(m, t, y, seed=3) for m in decay.MODELS}
    best = min(fits.values(), key=lambda f: f["aicc"])
    # power_law_floor nests power_law (c -> 0), so either is an acceptable win.
    assert best["model"] in {"power_law", "power_law_floor"}
    assert fits["exponential"]["aicc"] > fits["power_law"]["aicc"]


def test_floor_is_detected_when_present():
    model = decay.PowerLawFloor()
    t, y = _poisson_series(model, [600.0, 1.4, 12.0], n_months=200, seed=11)
    fit = decay.fit_model(model, t, y, seed=11)
    assert fit["_params"][2] == pytest.approx(12.0, rel=0.35)
    plain = decay.fit_model(decay.PowerLaw(), t, y, seed=11)
    assert fit["aicc"] < plain["aicc"]


def test_floor_is_not_invented_when_absent():
    """Guards the headline 'articles decay onto a floor' claim against
    the model simply always fitting a positive constant."""
    model = decay.PowerLaw()
    t, y = _poisson_series(model, [800.0, 1.5], n_months=220, seed=5)
    fit = decay.fit_model(decay.PowerLawFloor(), t, y, seed=5)
    assert fit["_params"][2] < 0.5


def test_aicc_penalises_extra_parameters():
    a = decay.aicc(nll=100.0, n_params=2, n_obs=50)
    b = decay.aicc(nll=100.0, n_params=3, n_obs=50)
    assert b > a


def test_temporal_gini_bounds():
    concentrated = np.zeros(60)
    concentrated[0] = 500
    even = np.full(60, 10.0)
    assert decay.temporal_gini(concentrated) > 0.9
    assert decay.temporal_gini(even) == pytest.approx(0.0, abs=1e-9)
    assert np.isnan(decay.temporal_gini(np.zeros(10)))


def test_empirical_half_life_ordering():
    t = np.arange(180, dtype=float)
    fast = 500 * np.power(t + 1, -2.0)
    slow = 500 * np.power(t + 1, -0.5)
    assert decay.empirical_half_life(fast) < decay.empirical_half_life(slow)


def test_curve_half_life_is_infinite_with_a_high_floor():
    model = decay.PowerLawFloor()
    # mu(0) = A + c. The curve can only halve if c < (A + c) / 2, i.e. c < A.
    never = np.array([10.0, 1.5, 15.0])
    assert np.isinf(decay.curve_half_life(model, never))
    eventually = np.array([10.0, 1.5, 2.0])
    assert np.isfinite(decay.curve_half_life(model, eventually))


def test_fit_article_rejects_short_or_empty_series():
    assert decay.fit_article(np.arange(10.0), np.ones(10)) is None
    assert decay.fit_article(np.arange(60.0), np.zeros(60)) is None


def test_fit_article_returns_normalised_akaike_weights():
    model = decay.PowerLawFloor()
    t, y = _poisson_series(model, [400.0, 1.2, 6.0], n_months=150, seed=2)
    row = decay.fit_article(t, y, seed=2)
    assert row is not None
    weights = [row[f"weight_{m.name}"] for m in decay.MODELS]
    assert sum(weights) == pytest.approx(1.0)
    assert row["best_pseudo_r2"] > 0.5


def test_fit_panel_shapes():
    rows = []
    for i in range(4):
        t, y = _poisson_series(decay.PowerLaw(), [300.0, 1.0 + 0.2 * i], seed=i)
        rows.append(
            pd.DataFrame(
                {
                    "title": f"Event {i}",
                    "month_index": t.astype(int),
                    "edits": y,
                    "event_class": "test",
                }
            )
        )
    panel = pd.concat(rows, ignore_index=True)
    fits = decay.fit_panel(panel)
    assert len(fits) == 4
    assert {"title", "event_class", "best_model"} <= set(fits.columns)
    # Steeper true exponent must produce a shorter estimated half-life.
    ordered = fits.sort_values("title")["empirical_half_life"].to_numpy()
    assert ordered[0] >= ordered[-1]
