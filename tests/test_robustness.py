# End-to-end recovery gates
# --------------------------------------------------------------------------


@pytest.fixture(scope="module")
def simulated_fits():
    data = simulate.simulate_corpus(n_articles=120, seed=21)
    panel = build_panel(data["corpus"], data["revisions"])
    fits = decay.fit_panel(panel, seed=21)
    return fits, data["ground_truth"]


def test_estimator_recovery_meets_the_published_thresholds(simulated_fits):
    """If this fails, the numbers in the report are not trustworthy."""
    fits, truth = simulated_fits
    report = simulate.validate_recovery(fits, truth)
    assert report["exponent"]["spearman"] > 0.55
    assert report["half_life_empirical"]["spearman"] > 0.55
    assert report["half_life_fitted"]["spearman"] > 0.55


def test_generating_family_is_usually_selected(simulated_fits):
    """Data are generated by a power law onto a floor; the selector should
    mostly land in that family rather than on an exponential."""
    fits, _ = simulated_fits
    share = fits["best_model"].value_counts(normalize=True)
    power_family = share.get("power_law_floor", 0) + share.get("power_law", 0)
    assert power_family > 0.55
    assert share.get("exponential", 0) < 0.30


def test_class_ordering_is_recovered(simulated_fits):
    """The headline claim is comparative, so the comparison must survive
    the whole pipeline, not just the fit."""
    fits, truth = simulated_fits
    merged = fits.merge(truth.drop(columns=["event_class"]), on="title")
    fast = merged[merged["event_class"] == "culture_award"]["empirical_half_life"]
    slow = merged[merged["event_class"] == "armed_conflict"]["empirical_half_life"]
    assert fast.median() < slow.median()
