"""Tests for the two corrections that made the estimators usable.

Both were found by validating against the simulator rather than by reading the
code, and both are load-bearing for the reported numbers -- so they get tests
that fail loudly if anyone reverts them.
"""

from __future__ import annotations

import numpy as np
import pandas as pd
import pytest

from imd import decay, simulate
from imd.collect import build_panel


def _series_with_resurgence(exponent=1.4, bump_at=36, bump_size=400, n=180, seed=0):
    rng = np.random.default_rng(seed)
    t = np.arange(n, dtype=float)
    mu = 400 * np.power(t + 1, -exponent) + 1.0
    mu = mu + bump_size * np.exp(-0.5 * ((t - bump_at) / 2.0) ** 2)
    return t, rng.poisson(mu).astype(float)


# --------------------------------------------------------------------------
# Peak detection
# --------------------------------------------------------------------------


def test_peak_search_ignores_a_later_resurgence():
    """A 10th-anniversary spike is not the event's attention peak."""
    _, y = _series_with_resurgence(bump_at=120, bump_size=5000, seed=1)
    assert np.argmax(y) > 100  # the raw argmax is fooled
    assert decay.find_peak(y) < 12  # the constrained search is not


def test_peak_search_still_finds_a_delayed_genuine_peak():
    y = np.zeros(120)
    y[:4] = 5
    y[4:8] = 200  # the story broke a few months late
    y[8:] = 3
    assert 3 <= decay.find_peak(y) <= 8


def test_peak_search_window_is_configurable():
    y = np.zeros(60)
    y[30] = 1000
    # The centred smoother spreads the spike over its neighbours.
    assert decay.find_peak(y, search_months=60) in (29, 30, 31)
    assert decay.find_peak(y, search_months=12) < 12


# --------------------------------------------------------------------------
# Resurgence trimming
# --------------------------------------------------------------------------


def test_trimming_recovers_the_exponent_a_resurgence_hides():
    t, y = _series_with_resurgence(exponent=1.4, seed=2)
    naive = decay.fit_model(decay.PowerLaw(), t, y, seed=2, trim_resurgences=False)
    trimmed = decay.fit_model(decay.PowerLaw(), t, y, seed=2, trim_resurgences=True)
    assert trimmed["n_trimmed"] > 0
    assert abs(trimmed["_params"][1] - 1.4) < abs(naive["_params"][1] - 1.4)


def test_trimming_is_inert_on_a_clean_series():
    rng = np.random.default_rng(3)
    t = np.arange(160, dtype=float)
    y = rng.poisson(500 * np.power(t + 1, -1.2) + 0.5).astype(float)
    clean = decay.fit_model(decay.PowerLaw(), t, y, seed=3, trim_resurgences=False)
    trimmed = decay.fit_model(decay.PowerLaw(), t, y, seed=3, trim_resurgences=True)
    assert trimmed["_params"][1] == pytest.approx(clean["_params"][1], rel=0.12)


def test_trimming_never_removes_quiet_months():
    """Downward deviations are signal, not outliers -- trimming them would
    manufacture persistence out of silence."""
    t = np.arange(120, dtype=float)
    y = (500 * np.power(t + 1, -1.2)).astype(float)
    y[40:60] = 0.0  # a genuine two-year silence
    fit = decay.fit_model(decay.PowerLaw(), t, y, seed=4, trim_resurgences=True)
    assert fit["n_trimmed"] == 0


def test_trimming_refuses_when_it_would_gut_the_series():
    t = np.arange(40, dtype=float)
    y = np.full(40, 1.0)
    y[::2] = 500.0  # half the series would be trimmed
    fit = decay.fit_model(decay.PowerLaw(), t, y, seed=5, trim_resurgences=True)
    assert fit["n_trimmed"] == 0


